#!/usr/bin/env node
// Tests cannot import a .log file, so the logs are embedded in one generated module:
// node scripts/build-fixtures.mjs   (rerun after adding or changing a log)
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('../tests/fixtures/', import.meta.url).pathname
const out = {}
for (const kind of readdirSync(root)) {
  const dir = join(root, kind)
  if (!statSync(dir).isDirectory() || kind === 'jsonl') continue
  for (const name of readdirSync(dir).filter(n => n.endsWith('.log'))) {
    out[`${kind}/${name}`] = readFileSync(join(dir, name), 'utf8')
  }
}
writeFileSync(
  join(root, 'logs.gen.ts'),
  `// Generated by scripts/build-fixtures.mjs from tests/fixtures/*/*.log. Do not edit.\nexport const LOGS: Record<string, string> = ${JSON.stringify(out, null, 1)}\n`,
)
console.log(Object.keys(out).join('\n'))
